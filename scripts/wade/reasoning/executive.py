"""Phase 8D: WADE Executive Reasoning.

Generates customer-safe executive summaries from finding sets.
No scare tactics, no unsupported claims, no jargon.
Advisory only — does NOT modify production findings.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from scripts.wade.reasoning.models import Finding, PriorityLevel


